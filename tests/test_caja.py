def test_coordinacion_no_entra_en_caja():
    app = FastAPI()
    app.include_router(caja.router, prefix="/api")

    async def fake_user():
        return actor(str(uuid.uuid4()), role="coordinator")
    app.dependency_overrides[deps.get_current_user] = fake_user

    async def req():
        async with AsyncClient(transport=ASGITransport(app=app), base_url="http://t") as c:
            return await c.get("/api/caja/dia")
    assert run(req()).status_code == 403


