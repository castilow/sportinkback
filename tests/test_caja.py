@pytest.fixture
def database(monkeypatch):
    dsn = os.environ.get("CAJA_TEST_DATABASE_URL") or os.environ.get("STOCK_TEST_DATABASE_URL")
    if not dsn:
        pytest.skip("Requiere Postgres temporal: CAJA_TEST_DATABASE_URL")
    from psycopg.conninfo import conninfo_to_dict
    if conninfo_to_dict(dsn).get("host", "") not in ("localhost", "127.0.0.1", "::1"):
        pytest.fail("Las pruebas de caja solo permiten Postgres local temporal")
    club = str(uuid.uuid4())
    with patch.object(postgres_compat.PostgresCompatDB, "_ensure_schema", lambda self: None):
        db = postgres_compat.PostgresCompatDB(dsn)
    monkeypatch.setattr(caja, "db", db)
    monkeypatch.setattr(stock, "db", db)
    with psycopg.connect(dsn) as conn:
        conn.execute("create table if not exists public.app_documents (row_id bigint generated by default as identity primary key, collection text not null, doc jsonb not null, created_at timestamptz not null default now(), updated_at timestamptz not null default now())")
    yield SimpleNamespace(dsn=dsn, club=club, user=actor(club))
    with psycopg.connect(dsn) as conn:
        conn.execute("delete from public.app_documents where doc->>'club_id' = %s", (club,))


def cobro(s, **kw):
    base = dict(tipo="ingreso", fecha="2026-11-25", concepto="indumentaria", opcion="Común",
                nombre="Familia García", importe=335, pago="efectivo")
    base.update(kw)
    return run(caja.create_movimiento(caja.MovimientoIn(**base), user=s.user))


def test_numeracion_por_entidad_e_iva(database):
    a = cobro(database)
    b = cobro(database, concepto="abono", opcion="", importe=110, pago="tarjeta")
    f = cobro(database, concepto="cuota", opcion="", importe=50)
    g = run(caja.create_movimiento(caja.MovimientoIn(tipo="gasto", fecha="2026-11-25", descripcion="Compra de material",
                                                     importe=20, pago="efectivo"), user=database.user))
    assert [a["numero"], b["numero"], f["numero"], g["numero"]] == ["SAD-2026-00001", "SAD-2026-00002", "FUN-2026-00001", "SAL-2026-00001"]
    assert a["iva"] == 21 and a["base"] == 276.86 and a["cuota_iva"] == 58.14
    assert b["iva"] == 10 and b["base"] == 100.0
    assert f["iva"] == 0 and f["entidad"] == "Fundación"
    assert a["concepto_nombre"] == "Indumentaria · Común"


def test_validaciones(database):
    with pytest.raises(HTTPException) as e:
        cobro(database, nombre="")
    assert "nombre" in e.value.detail
    t = cobro(database, concepto="taquilla", opcion="", nombre="", importe=10)  # taquilla no pide nombre
    assert t["numero"].startswith("SAD-")
    with pytest.raises(HTTPException):
        cobro(database, concepto="otro", opcion="", entidad="SAD")  # «Otro» exige texto
    with pytest.raises(HTTPException):
        cobro(database, concepto="jugadores_internacionales", opcion="")  # sin entidad por defecto
    m = cobro(database, importe=335, entregado=350)
    assert m["cambio"] == 15.0
    with pytest.raises(HTTPException):
        cobro(database, importe=335, entregado=300)


def test_cobros_concurrentes_numeros_unicos(database):
    with ThreadPoolExecutor(max_workers=8) as ex:
        res = list(ex.map(lambda _: cobro(database, importe=10), range(16)))
    nums = sorted(r["numero"] for r in res)
    assert nums == [f"SAD-2026-{i:05d}" for i in range(1, 17)]


def test_anular_editar_y_cierre(database):
    a = cobro(database, importe=100, pago="efectivo")
    b = cobro(database, importe=50, pago="mixto", efectivo=20, tarjeta=30)
    run(caja.create_movimiento(caja.MovimientoIn(tipo="gasto", fecha="2026-11-25", descripcion="Cambio",
                                                 importe=5, pago="efectivo"), user=database.user))
    e = run(caja.update_movimiento(a["id"], caja.MovimientoUpdateIn(nombre="Familia López", importe=120),
                                   user=database.user))
    assert e["nombre"] == "Familia López" and e["importe"] == 120 and e["efectivo"] == 120
    assert e["cambios"][-1]["campos"]["nombre"] == ["Familia García", "Familia López"]
    an = run(caja.anular_movimiento(b["id"], caja.AnularIn(motivo="Cobrado dos veces"), user=database.user))
    assert an["estado"] == "anulado"
    with pytest.raises(HTTPException):
        run(caja.update_movimiento(b["id"], caja.MovimientoUpdateIn(nota="x"), user=database.user))
    dia = run(caja.caja_dia(fecha="2026-11-25", user=database.user))
    assert dia["totales"]["ingresos"] == 120 and dia["totales"]["num_anulados"] == 1
    c = run(caja.cerrar_caja(caja.CierreIn(fecha="2026-11-25", fondo_inicial=50, efectivo_contado=160),
                             user=database.user))
    assert c["esperado"] == 50 + 120 - 5 and c["descuadre"] == -5
    with pytest.raises(HTTPException) as err:
        cobro(database)
    assert "cerrada" in err.value.detail
    run(caja.reabrir_caja("2026-11-25", caja.AnularIn(motivo="Faltaba un cobro"), user=database.user))
    assert cobro(database)["numero"] == "SAD-2026-00003"
    # Los números no se reutilizan aunque haya anulados
    assert run(caja.caja_dia(fecha="2026-11-25", user=database.user))["cierre"] is None


def test_prendas_descuentan_y_vuelven_al_stock(database):
    p = run(stock.create_product(stock.ProductIn(ean="5715598626222", name="Sudadera", size="2XL"), {**database.user, "role": "admin"}))
    run(stock.create_movement(stock.MovementIn(type="entrada", items=[{"ean": "5715598626222", "qty": 2}]), {**database.user, "role": "admin"}))
    with pytest.raises(HTTPException) as e:
        cobro(database, prendas=[{"ean": "5715598626222", "qty": 5}])
    assert "stock" in e.value.detail.lower()
    # el intento fallido no consume número
    m = cobro(database, prendas=[{"ean": "5715598626222", "qty": 1}])
    assert m["numero"] == "SAD-2026-00001" and m["prendas"][0]["qty"] == 1
    prods = {x["id"]: x for x in run(stock.list_products(user={**database.user, "role": "admin"}))}
    assert prods[p["id"]]["stock"] == 1
    run(caja.anular_movimiento(m["id"], caja.AnularIn(motivo="Devuelta"), user=database.user))
    prods = {x["id"]: x for x in run(stock.list_products(user={**database.user, "role": "admin"}))}
    assert prods[p["id"]]["stock"] == 2


def test_config_personalizada(database):
    cfg = run(caja.get_config(user=database.user))
    cfg["conceptos"][0]["opciones"][0]["precio"] = 350
    cfg["conceptos"].append({"nombre": "Campus de verano", "entidad": "Fundación", "iva": None, "pide_nombre": True})
    out = run(caja.put_config(caja.ConfigIn(**cfg), user=database.user))
    assert out["conceptos"][0]["opciones"][0]["precio"] == 350
    assert any(c["key"] == "campus_de_verano" for c in out["conceptos"])
    m = cobro(database, concepto="campus_de_verano", opcion="", importe=180)
    assert m["numero"].startswith("FUN-")


def test_export_e_import_historial(database):
    cobro(database)
    resp = run(caja.export_xlsx(desde="2026-11-01", hasta="2026-11-30", user=database.user))

    async def body():
        return b"".join([c async for c in resp.body_iterator])
    data = run(body())
    from openpyxl import load_workbook
    wb = load_workbook(io.BytesIO(data))
    assert wb["Movimientos"].max_row == 2 and wb["Movimientos"]["C2"].value == "SAD-2026-00001"

    import pandas as pd
    hist = pd.DataFrame([
        {"Fecha": "2026-09-08", "Origen": "Mostrador · 12:26", "Entidad": "SAD", "Concepto": "Indumentaria · Común",
         "Nombre": "Marcos Sánchez", "Importe": 335, "Pago": "Efectivo", "Tipo": "Ingreso", "Nota": "",
         "Cobrado en efectivo": 335, "Cobrado en tarjeta": 0, "ID": "1788949611067-tbfkz", "% IVA": 21},
        {"Fecha": "2026-09-08", "Origen": "Mostrador · 13:00", "Entidad": "", "Concepto": "Cambio",
         "Nombre": "", "Importe": -20, "Pago": "Efectivo", "Tipo": "Gasto", "Nota": "",
         "Cobrado en efectivo": 0, "Cobrado en tarjeta": 0, "ID": "1788949611999-aaaaa", "% IVA": ""},
    ])
    buf = io.BytesIO()
    with pd.ExcelWriter(buf, engine="openpyxl") as w:
        hist.to_excel(w, index=False, sheet_name="Movimientos")
    raw = buf.getvalue()
    r1 = run(caja.import_historial(file=UploadFile(file=io.BytesIO(raw), filename="caja.xlsx"), user=database.user))
    r2 = run(caja.import_historial(file=UploadFile(file=io.BytesIO(raw), filename="caja.xlsx"), user=database.user))
    assert (r1["importados"], r2["importados"], r2["repetidos"]) == (2, 0, 2)
    lst = run(caja.list_movimientos(desde="2026-09-08", hasta="2026-09-08", user=database.user))
    assert lst["totales"]["ingresos"] == 335 and lst["totales"]["gastos"] == 20
    assert {m["hora"] for m in lst["movimientos"]} == {"12:26", "13:00"}
    assert run(caja.list_movimientos(desde="2026-09-01", hasta="2026-09-30", q="marcos", user=database.user))["movimientos"][0]["nombre"] == "Marcos Sánchez"
