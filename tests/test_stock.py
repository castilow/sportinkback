# Se ejecuta tanto como tests/test_stock.py dentro del backend como desde la
# copia de trabajo temporal pasando BACKEND_SOURCE=/ruta/al/backend.
BACKEND = os.environ.get("BACKEND_SOURCE", str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, BACKEND)
import postgres_compat
with patch.dict(os.environ, {"DATABASE_URL": "postgresql://offline:offline@localhost/offline"}), \
     patch.object(postgres_compat.PostgresCompatDB, "_ensure_schema", lambda self: None):
    import deps
    local_stock = Path(__file__).with_name("stock.py")
    if local_stock.exists():
        spec = importlib.util.spec_from_file_location("stock_under_test", local_stock)
        stock = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(stock)
    else:
        stock = importlib.import_module("routes.stock")


def actor(club=None, role="admin"):
    return {"id": "test-user", "role": role, "club_id": club or str(uuid.uuid4()), "name": "Prueba"}


def run(coro):
    return asyncio.run(coro)


def movement(kind, *items):
    return stock.MovementIn(type=kind, items=list(items))


def test_ean_keeps_leading_zeroes_and_normalizes_spaces():
    data = stock.ProductIn(ean=" 0012 3456 ", name="Camiseta")
    assert data.ean == "00123456"
    with pytest.raises(ValidationError):
        stock.ProductIn(ean="123x", name="Camiseta")
    with pytest.raises(ValidationError):
        movement("salida", {"ean": "00123456", "qty": -1})


def test_mongo_write_fails_explicitly_before_any_connection(monkeypatch):
    monkeypatch.setattr(stock, "db", object())
    def forbidden(*args, **kwargs):
        raise AssertionError("No debe abrir conexión")
    monkeypatch.setattr(stock.psycopg, "connect", forbidden)
    with pytest.raises(HTTPException) as e:
        run(stock.create_product(stock.ProductIn(ean="00123456", name="Camiseta"), actor()))
    assert e.value.status_code == 503


@pytest.mark.parametrize("role", ["coordinator", "coach", "pending"])
def test_readonly_roles_cannot_write_stock(role, monkeypatch):
    app = FastAPI()
    app.include_router(stock.router, prefix="/api")
    app.dependency_overrides[deps.get_current_user] = lambda: actor(role=role)
    def forbidden(*args, **kwargs):
        raise AssertionError("La escritura no debe llegar a la base de datos")
    monkeypatch.setattr(stock, "_run_stock_transaction", forbidden)
    async def request():
        async with AsyncClient(transport=ASGITransport(app=app), base_url="http://offline") as client:
            return await client.post("/api/stock/products", json={"ean": "00123456", "name": "Camiseta"})
    assert run(request()).status_code == 403


@pytest.fixture
def database(monkeypatch):
    dsn = os.environ.get("STOCK_TEST_DATABASE_URL")
    if not dsn:
        pytest.skip("Requiere Postgres temporal explícito: STOCK_TEST_DATABASE_URL")
    # Evita ejecutar accidentalmente contra un servidor externo/producción.
    from psycopg.conninfo import conninfo_to_dict
    info = conninfo_to_dict(dsn)
    if info.get("host", "") not in ("localhost", "127.0.0.1", "::1") and not info.get("host", "").startswith("/private/tmp/"):
        pytest.fail("Las pruebas stock solo permiten Postgres local temporal")
    club = str(uuid.uuid4())
    with patch.object(postgres_compat.PostgresCompatDB, "_ensure_schema", lambda self: None):
        db = postgres_compat.PostgresCompatDB(dsn)
    monkeypatch.setattr(stock, "db", db)
    with psycopg.connect(dsn) as conn:
        conn.execute("create table if not exists public.app_documents (row_id bigint generated by default as identity primary key, collection text not null, doc jsonb not null, created_at timestamptz not null default now(), updated_at timestamptz not null default now())")
    state = SimpleNamespace(dsn=dsn, actor=actor(club), club=club)
    yield state
    with psycopg.connect(dsn) as conn:
        conn.execute("delete from public.app_documents where doc->>'club_id' = %s", (club,))


def rows(state, collection="stock_products"):
    with psycopg.connect(state.dsn) as conn:
        return [r[0] for r in conn.execute("select doc from public.app_documents where collection=%s and doc->>'club_id'=%s order by row_id", (collection, state.club)).fetchall()]


def create(state, ean="00123456", name="Camiseta"):
    return run(stock.create_product(stock.ProductIn(ean=ean, name=name, size="M"), state.actor))


def move(state, kind, *items):
    return run(stock.create_movement(movement(kind, *items), state.actor))


def test_entries_outgoing_counts_and_duplicate_scans(database):
    p = create(database)
    incoming = move(database, "entrada", {"ean": p["ean"], "qty": 3}, {"product_id": p["id"], "qty": 2})
    assert incoming["units"] == 5
    assert len(incoming["items"]) == 1
    assert incoming["items"][0]["stock_before"] == 0
    assert incoming["items"][0]["stock_after"] == 5
    outgoing = move(database, "salida", {"product_id": p["id"], "qty": 2})
    assert outgoing["items"][0]["stock_after"] == 3
    count = move(database, "ajuste", {"ean": p["ean"], "qty": 0})
    assert count["items"][0]["qty"] == -3
    assert rows(database)[0]["stock"] == 0
    assert len(rows(database, "stock_movements")) == 3


def test_insufficient_line_rejects_whole_batch(database):
    first = create(database)
    second = create(database, "00123457", "Pantalón")
    move(database, "entrada", {"product_id": first["id"], "qty": 5})
    with pytest.raises(HTTPException) as e:
        move(database, "salida", {"product_id": first["id"], "qty": 1}, {"product_id": second["id"], "qty": 1})
    assert e.value.status_code == 409
    assert {p["id"]: p["stock"] for p in rows(database)} == {first["id"]: 5, second["id"]: 0}
    assert len(rows(database, "stock_movements")) == 1


def test_failure_writing_history_rolls_back_stock(database, monkeypatch):
    p = create(database)
    original = stock._insert_document
    def fail_history(cur, collection, doc):
        if collection == "stock_movements":
            # Error SQL real: la conexión pasa a estado abortado y debe revertir.
            cur.execute("select 1 / 0")
        return original(cur, collection, doc)
    monkeypatch.setattr(stock, "_insert_document", fail_history)
    with pytest.raises(psycopg.errors.DivisionByZero):
        move(database, "entrada", {"product_id": p["id"], "qty": 5})
    assert rows(database)[0]["stock"] == 0
    assert rows(database, "stock_movements") == []


def test_two_concurrent_outgoing_only_one_can_consume_balance(database):
    p = create(database)
    move(database, "entrada", {"product_id": p["id"], "qty": 5})
    async def simultaneous():
        return await asyncio.gather(*[
            stock.create_movement(movement("salida", {"product_id": p["id"], "qty": 4}), database.actor)
            for _ in range(2)
        ], return_exceptions=True)
    result = run(simultaneous())
    assert sum(isinstance(r, dict) for r in result) == 1
    errors = [r for r in result if isinstance(r, HTTPException)]
    assert len(errors) == 1 and errors[0].status_code == 409
    assert rows(database)[0]["stock"] == 1
    assert len(rows(database, "stock_movements")) == 2


def test_two_concurrent_product_creations_keep_one_ean(database):
    async def simultaneous():
        return await asyncio.gather(*[
            stock.create_product(stock.ProductIn(ean="00123456", name="Camiseta"), database.actor)
            for _ in range(2)
        ], return_exceptions=True)
    result = run(simultaneous())
    assert sum(isinstance(r, dict) for r in result) == 1
    errors = [r for r in result if isinstance(r, HTTPException)]
    assert len(errors) == 1 and errors[0].status_code == 409
    assert len(rows(database)) == 1


def test_import_preserves_stock_and_reports_repeated_rows(database):
    p = create(database)
    move(database, "entrada", {"product_id": p["id"], "qty": 7})
    content = "EAN,Nombre,Talla\n00123456,Camiseta nueva,L\n00123457,Pantalón,S\n00123457,Repetido,M\ninvalid,Error,M\n".encode()
    result = run(stock.import_products(UploadFile(filename="catalog.csv", file=io.BytesIO(content)), database.actor))
    assert result["updated"] == 1 and result["created"] == 1
    assert result["error_count"] == 2
    products = {p["ean"]: p for p in rows(database)}
    assert products["00123456"]["stock"] == 7
    assert products["00123456"]["name"] == "Camiseta nueva"
    assert products["00123457"]["stock"] == 0


def test_other_club_product_cannot_be_changed(database):
    p = create(database)
    other = actor()
    with pytest.raises(HTTPException) as e:
        run(stock.create_movement(movement("entrada", {"product_id": p["id"], "qty": 2}), other))
    assert e.value.status_code == 404
    assert rows(database)[0]["stock"] == 0
    assert rows(database, "stock_movements") == []
