"""Stock: pruebas offline y transacciones reales en una BD temporal explícita.

Sin DSN: solo modelos, permisos y rechazo de Mongo (sin red ni .env).
Con STOCK_TEST_DATABASE_URL: usa un Postgres DE PRUEBAS aislado; no borra otras
colecciones ni otros clubes. Cada prueba usa un club UUID y limpia sus filas.
"""
